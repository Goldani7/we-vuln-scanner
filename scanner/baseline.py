"""Comparison across runs (--baseline).

Compares the current findings against a previous JSON report (generated with `-o x.json`) by
`fingerprint` (rule + title + target). Lets CI fail only on NEW findings instead of repeating the
same alert on every run, and shows what got fixed.
`info` findings (confirmations and context) never enter the comparison.
Note: the title is part of the fingerprint. If a finding's title changes (e.g. a CVE's CVSS or
EPSS score shows up in the title), it counts as both "resolved" and "new": that is a risk change
worth reviewing.
"""
import dataclasses
import json
from dataclasses import dataclass, field

from .finding import Severity


class BaselineError(Exception):
    """Baseline file missing, unreadable, or in an unexpected format."""


@dataclass
class Comparison:
    file: str = ""
    new: list = field(default_factory=list)
    unchanged: list = field(default_factory=list)
    resolved: list = field(default_factory=list)  # dicts from the previous report

    def summary(self) -> dict:
        return {
            "file": self.file, "new": len(self.new), "unchanged": len(self.unchanged),
            "resolved": len(self.resolved),
            "resolved_findings": [{"fingerprint": r["fingerprint"], "title": r.get("title", ""),
                                   "severity": r.get("severity", ""), "rule_id": r.get("rule_id", "")}
                                  for r in self.resolved],
        }


def load_baseline(path: str) -> dict:
    """{fingerprint: finding_dict} from the previous report (either versioned object or plain list)."""
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except OSError as e:
        raise BaselineError(f"could not read baseline '{path}': {e.strerror or e}") from e
    except ValueError as e:
        raise BaselineError(f"baseline '{path}' is not valid JSON: {e}") from e

    items = data.get("findings") if isinstance(data, dict) else data
    if not isinstance(items, list):
        raise BaselineError(f"baseline '{path}' does not contain a list of findings "
                            "(use a report generated with -o report.json)")
    out = {}
    for item in items:
        if not isinstance(item, dict) or not item.get("fingerprint"):
            raise BaselineError(f"baseline '{path}' has findings without a 'fingerprint': "
                                "was it generated by an older version of the tool?")
        out[item["fingerprint"]] = item
    return out


def compare(findings, baseline: dict, path: str = "") -> Comparison:
    cmp = Comparison(file=path)
    current = set()
    for f in findings:
        if f.severity is Severity.INFO:
            continue
        current.add(f.fingerprint)
        (cmp.unchanged if f.fingerprint in baseline else cmp.new).append(f)
    cmp.resolved = [item for fp, item in baseline.items()
                    if fp not in current and item.get("severity") != Severity.INFO.value]
    return cmp


def annotate(findings, cmp: Comparison) -> list:
    """Copies of the findings with `status` = "new" | "unchanged" (INFO is left without a status)."""
    new = {f.fingerprint for f in cmp.new}
    unchanged = {f.fingerprint for f in cmp.unchanged}
    return [dataclasses.replace(f, status="new" if f.fingerprint in new and f.severity is not Severity.INFO
                                else "unchanged" if f.fingerprint in unchanged and f.severity is not Severity.INFO
                                else "") for f in findings]
